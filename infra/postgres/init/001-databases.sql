-- Executed only when the named PostgreSQL volume is empty.
-- psql reads passwords from the environment; :'variable' quotes SQL literals.
-- Isolated application databases and logins.
\set ON_ERROR_STOP on
\set ECHO none
\set QUIET on
\getenv user_password TOQ_USER_DB_PASSWORD
\getenv recipe_password TOQ_RECIPE_DB_PASSWORD
\getenv nutrition_password TOQ_NUTRITION_DB_PASSWORD
\getenv planner_password TOQ_PLANNER_DB_PASSWORD
\getenv social_password TOQ_SOCIAL_DB_PASSWORD
\getenv keycloak_password KEYCLOAK_DB_PASSWORD

CREATE ROLE toq_user_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD :'user_password';
CREATE ROLE toq_recipe_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD :'recipe_password';
CREATE ROLE toq_nutrition_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD :'nutrition_password';
CREATE ROLE toq_planner_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD :'planner_password';
CREATE ROLE toq_social_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD :'social_password';
CREATE ROLE keycloak_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD :'keycloak_password';

REVOKE ALL ON DATABASE postgres FROM PUBLIC;
REVOKE ALL ON DATABASE template1 FROM PUBLIC;

CREATE DATABASE toq_user OWNER toq_user_app;
CREATE DATABASE toq_recipe OWNER toq_recipe_app;
CREATE DATABASE toq_nutrition OWNER toq_nutrition_app;
CREATE DATABASE toq_planner OWNER toq_planner_app;
CREATE DATABASE toq_social OWNER toq_social_app;
CREATE DATABASE keycloak OWNER keycloak_app;

REVOKE ALL ON DATABASE toq_user FROM PUBLIC;
REVOKE ALL ON DATABASE toq_recipe FROM PUBLIC;
REVOKE ALL ON DATABASE toq_nutrition FROM PUBLIC;
REVOKE ALL ON DATABASE toq_planner FROM PUBLIC;
REVOKE ALL ON DATABASE toq_social FROM PUBLIC;
REVOKE ALL ON DATABASE keycloak FROM PUBLIC;

\connect toq_user
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO toq_user_app;
ALTER DEFAULT PRIVILEGES FOR ROLE toq_user_app IN SCHEMA public REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;

\connect toq_recipe
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO toq_recipe_app;
ALTER DEFAULT PRIVILEGES FOR ROLE toq_recipe_app IN SCHEMA public REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;

\connect toq_nutrition
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO toq_nutrition_app;
ALTER DEFAULT PRIVILEGES FOR ROLE toq_nutrition_app IN SCHEMA public REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;

\connect toq_planner
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO toq_planner_app;
ALTER DEFAULT PRIVILEGES FOR ROLE toq_planner_app IN SCHEMA public REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;

\connect keycloak
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO keycloak_app;
ALTER DEFAULT PRIVILEGES FOR ROLE keycloak_app IN SCHEMA public REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;

\connect toq_social
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO toq_social_app;
ALTER DEFAULT PRIVILEGES FOR ROLE toq_social_app IN SCHEMA public REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
